<?php
// ============================================================================
// Migracion de la base MySQL historica del "Sistema 171" (ven911_2025) hacia
// PostgreSQL, en el esquema "historico" de la base principal ven911.
//
// Uso (desde la raiz del proyecto, por consola):
//     php database/migrar_mysql_a_postgres.php
//
// Lee las credenciales de config/conexion_local.php (PostgreSQL y MySQL).
// Es repetible: borra y vuelve a crear el esquema "historico".
//
// Conversiones:
//   - Nombres de columnas en minusculas (codAmigo -> codamigo).
//   - char(n) -> varchar(n): MySQL quita los espacios finales de CHAR y
//     PostgreSQL los conserva; varchar mantiene el comportamiento anterior.
//   - tinyint -> smallint, int -> integer, auto_increment -> identity.
//   - Fechas '0000-00-00' -> NULL.
// ============================================================================

if (PHP_SAPI !== 'cli') {
    http_response_code(403);
    exit("Este script solo se ejecuta por consola.\n");
}

require_once __DIR__ . '/../config/conexion_local.php';

$esquema = 'historico';

$pg = pg_connect("host=" . HOST . " port=" . PORT . " dbname=" . DATABASE . " user=" . USER . " password='" . PASSWORD . "' options='--client_encoding=UTF8'")
    or exit("No se pudo conectar a PostgreSQL\n");

mysqli_report(MYSQLI_REPORT_ERROR | MYSQLI_REPORT_STRICT);
$my = mysqli_connect(HOSTMYSQL, USERMYSQL, PASSWORDMYSQL, DATABASEMYSQL);
mysqli_set_charset($my, 'utf8mb4');
mysqli_query($my, "SET SESSION sql_mode = ''");

function tipo_pg($columna)
{
    $tipo = strtolower($columna['COLUMN_TYPE']);
    if (preg_match('/^(tiny|small)int/', $tipo)) return 'smallint';
    if (preg_match('/^(medium)?int/', $tipo)) return 'integer';
    if (preg_match('/^bigint/', $tipo)) return 'bigint';
    if (preg_match('/^(char|varchar)\((\d+)\)/', $tipo, $m)) return "varchar($m[2])";
    if (preg_match('/^(decimal|numeric)\((\d+),(\d+)\)/', $tipo, $m)) return "numeric($m[2],$m[3])";
    if (preg_match('/^(float|double)/', $tipo)) return 'double precision';
    if (preg_match('/text$/', $tipo)) return 'text';
    if ($tipo === 'date') return 'date';
    if ($tipo === 'time') return 'time';
    if (preg_match('/^(datetime|timestamp)/', $tipo)) return 'timestamp';
    if (preg_match('/^(enum|set)/', $tipo)) return 'text';
    if (preg_match('/blob$|binary/', $tipo)) return 'bytea';
    return 'text';
}

function valor_copy($valor, $tipo)
{
    if ($valor === null) return '\\N';
    if (($tipo === 'date' || $tipo === 'timestamp') && strpos($valor, '0000-00-00') === 0) return '\\N';
    return str_replace(["\\", "\t", "\n", "\r"], ["\\\\", "\\t", "\\n", "\\r"], $valor);
}

pg_query($pg, "BEGIN");
pg_query($pg, "DROP SCHEMA IF EXISTS $esquema CASCADE");
pg_query($pg, "CREATE SCHEMA $esquema");
pg_query($pg, "COMMENT ON SCHEMA $esquema IS 'Datos del Sistema 171 migrados desde MySQL (ven911_2025)'");

$tablas = mysqli_query($my, "SELECT table_name AS t FROM information_schema.tables WHERE table_schema = DATABASE() AND table_type = 'BASE TABLE' ORDER BY table_name");

while ($t = mysqli_fetch_assoc($tablas)) {
    $tabla = $t['t'];
    $tabla_pg = pg_escape_identifier($pg, strtolower($tabla));

    $res_cols = mysqli_query($my, "SELECT * FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = '" . mysqli_real_escape_string($my, $tabla) . "' ORDER BY ordinal_position");
    $columnas = [];
    $definiciones = [];
    $identidad = null;
    $pk = [];
    $indices = [];
    while ($c = mysqli_fetch_assoc($res_cols)) {
        $nombre = strtolower($c['COLUMN_NAME']);
        $tipo = tipo_pg($c);
        $def = pg_escape_identifier($pg, $nombre) . ' ' . $tipo;
        if (strpos($c['EXTRA'], 'auto_increment') !== false) {
            $def .= ' GENERATED BY DEFAULT AS IDENTITY';
            $identidad = $nombre;
        } elseif ($c['COLUMN_DEFAULT'] !== null && preg_match('/^-?\d+(\.\d+)?$/', $c['COLUMN_DEFAULT'])) {
            $def .= ' DEFAULT ' . $c['COLUMN_DEFAULT'];
        }
        // Las fechas pueden quedar en NULL al convertir '0000-00-00'
        if ($c['IS_NULLABLE'] === 'NO' && $tipo !== 'date' && $tipo !== 'timestamp') {
            $def .= ' NOT NULL';
        }
        if ($c['COLUMN_KEY'] === 'PRI') $pk[] = pg_escape_identifier($pg, $nombre);
        if ($c['COLUMN_KEY'] === 'MUL' || $c['COLUMN_KEY'] === 'UNI') $indices[$nombre] = $c['COLUMN_KEY'];
        $definiciones[] = $def;
        $columnas[] = ['origen' => $c['COLUMN_NAME'], 'tipo' => $tipo];
    }
    if ($pk) $definiciones[] = 'PRIMARY KEY (' . implode(', ', $pk) . ')';

    pg_query($pg, "CREATE TABLE $esquema.$tabla_pg (\n  " . implode(",\n  ", $definiciones) . "\n)")
        or exit("Error creando $tabla: " . pg_last_error($pg) . "\n");

    // Copia de datos por bloques con COPY
    $lista_origen = implode(', ', array_map(fn($c) => '`' . $c['origen'] . '`', $columnas));
    $datos = mysqli_query($my, "SELECT $lista_origen FROM `$tabla`", MYSQLI_USE_RESULT);
    $bloque = [];
    $total = 0;
    while ($fila = mysqli_fetch_row($datos)) {
        $linea = [];
        foreach ($fila as $i => $valor) {
            $linea[] = valor_copy($valor, $columnas[$i]['tipo']);
        }
        $bloque[] = implode("\t", $linea) . "\n";
        if (count($bloque) >= 5000) {
            pg_copy_from($pg, "$esquema.$tabla_pg", $bloque) or exit("Error copiando $tabla: " . pg_last_error($pg) . "\n");
            $total += count($bloque);
            $bloque = [];
        }
    }
    if ($bloque) {
        pg_copy_from($pg, "$esquema.$tabla_pg", $bloque) or exit("Error copiando $tabla: " . pg_last_error($pg) . "\n");
        $total += count($bloque);
    }
    mysqli_free_result($datos);

    foreach ($indices as $col => $clave) {
        $unico = $clave === 'UNI' ? 'UNIQUE ' : '';
        $nombre_idx = pg_escape_identifier($pg, 'idx_' . strtolower($tabla) . '_' . $col);
        pg_query($pg, "CREATE {$unico}INDEX $nombre_idx ON $esquema.$tabla_pg (" . pg_escape_identifier($pg, $col) . ")");
    }

    if ($identidad) {
        $col = pg_escape_identifier($pg, $identidad);
        pg_query($pg, "SELECT setval(pg_get_serial_sequence('$esquema.$tabla_pg', '$identidad'), COALESCE((SELECT MAX($col) FROM $esquema.$tabla_pg), 0) + 1, false)");
    }

    echo str_pad($tabla, 22) . " $total filas\n";
}

pg_query($pg, "COMMIT");
echo "Migracion completada en el esquema '$esquema' de la base " . DATABASE . ".\n";
