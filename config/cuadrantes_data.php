function buscar_cuadrantes($criterio) {
    $todos = get_todos_los_cuadrantes();
    if (empty($criterio)) return $todos;
    $criterio = mb_strtoupper(trim($criterio));
    $res = [];
    foreach ($todos as $c) {
        if (strpos(mb_strtoupper($c['cuadrante']), $criterio) !== false ||
            strpos(mb_strtoupper($c['municipio']), $criterio) !== false ||
            strpos(mb_strtoupper($c['parroquia']), $criterio) !== false ||
            strpos(mb_strtoupper($c['sectores']), $criterio) !== false ||
            strpos(mb_strtoupper($c['comuna']), $criterio) !== false ||
            strpos(mb_strtoupper($c['organismo']), $criterio) !== false ||
            strpos($c['telefono'], $criterio) !== false) {
            $res[] = $c;
        }
    }
    return $res;
}
